/**
 * 获取地点的本地化数据
 */
export function getLocalizedLocation(
  location: import('./locations').Location,
  locale: string
) {
  const zhData = locationsZhData[location.id];
  const normalizedLocale = locale.toLowerCase();

  if (normalizedLocale.startsWith('zh')) {
    // Use locationsZhData dictionary if available, otherwise fall back to inline zh fields
    return {
      ...location,
      name: location.nameZh || location.name,
      description: zhData?.descriptionZh || location.descriptionZh || location.description,
      fullDescription: zhData?.fullDescriptionZh || location.fullDescriptionZh || location.fullDescription,
      facts: (zhData?.factsZh && zhData.factsZh.length > 0)
        ? zhData.factsZh
        : (location.factsZh && location.factsZh.length > 0)
          ? location.factsZh
          : location.facts,
      address: zhData?.addressZh?.trim() || location.addressZh || location.address,
      visitInfo: location.visitInfo ? {
        ...location.visitInfo,
        hours: zhData?.hoursZh || location.visitInfo.hoursZh || location.visitInfo.hours,
        admission: zhData?.admissionZh || location.visitInfo.admissionZh || location.visitInfo.admission,
      } : undefined,
    };
  }

  return location;
}
